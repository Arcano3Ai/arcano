function getMinorCardImage(suit: string, num: number): string {
  const suitPrefix: Record<string, string> = {
    Bastos: "wa",
    Copas: "cu",
    Espadas: "sw",
    Oros: "pe",
  };
  const prefix = suitPrefix[suit] || "wa";
  let suffix = "";
  if (num === 1) suffix = "ac";
  else if (num >= 2 && num <= 10) suffix = String(num).padStart(2, "0");
  else if (num === 11) suffix = "pa";
  else if (num === 12) suffix = "kn";
  else if (num === 13) suffix = "qu";
  else if (num === 14) suffix = "ki";
  return `/images/cards/${prefix}${suffix}.webp`;
}

export const minorArcanaList: MinorArcanaCard[] = rawMinorArcanaList.map((card) => ({
  ...card,
  imageUrl: getMinorCardImage(card.suit, card.numberValue),
}));
